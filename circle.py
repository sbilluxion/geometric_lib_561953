import math


def area(r):
#Возвращает площадь круга в формате float
#	Параметры:
#		r: радиус окружности
#	Пример: area(10) = 314.1592653589793	

    return math.pi * r * r


def perimeter(r):
#Возвращает периметр круга в формате float
#	Параметры:
#		r: радиус окружности
#	Пример: perimeter(10) = 62.83185307179586
#
    return 2 * math.pi * r

